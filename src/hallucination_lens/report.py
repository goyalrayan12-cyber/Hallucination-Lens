"""Write a human-readable REPORT.md for one run (handy to paste into a README or a paper)."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from hallucination_lens import __version__
from hallucination_lens.features import FEATURE_DESCRIPTIONS


def _pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _num(x, nd: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def format_summary(m: dict) -> str:
    """Short console summary."""
    c, k = m["classifier"], m["conformal"]
    g = k[k["guardrail_variant"]]
    lines = [
        f"Run: {m['tag']}   ({m['backend']} / {m['model']}, labels: {m['label_method']})",
        f"Answers: {m['n']['total']}  (train {m['n']['train']}, calibration {m['n']['calibration']}, test {m['n']['test']})"
        f"   hallucinated share: {_pct(m['hallucinated_share'])}",
        f"Classifier ({m['classifier_name']}): accuracy {_pct(c['accuracy'])} "
        f"(always-guess-majority: {_pct(c['majority_baseline_accuracy'])}), AUROC {_num(c['auroc'])}, ECE {_num(c['ece'])}",
        f"Conformal ({k['guardrail_variant']}, target {_pct(k['target_coverage'])}): coverage {_pct(g['coverage'])}, "
        f"avg set size {_num(g['avg_set_size'], 2)}, TRUST {_pct(g['rate_trust'])}, "
        f"hallucinations wrongly stamped TRUST {_pct(g['false_reassurance_rate'])}",
    ]
    rs = m.get("repeated_splits") or {}
    if k["guardrail_variant"] in rs:
        r = rs[k["guardrail_variant"]]
        lines.append(
            f"Over {r['n_repeats']} random re-splits: mean coverage {_pct(r['coverage_mean'])} "
            f"(5th percentile {_pct(r['coverage_p05'])})"
        )
    return "\n".join(lines)


def write_report(run_path: Path, m: dict, figures: list[str]) -> Path:
    c, k = m["classifier"], m["conformal"]
    marg, cc = k["marginal"], k["class_conditional"]
    rs = m.get("repeated_splits") or {}
    out = [
        f"# Run report: `{m['tag']}`",
        f"_Generated by hallucination-lens {__version__} on {datetime.now():%Y-%m-%d %H:%M}._",
        "",
        "## Setup",
        f"- Answering model: **{m['model']}** ({m['backend']} backend)",
        f"- Label method: **{m['label_method']}**",
        f"- Classifier: **{m['classifier_name']}** on {len(m['feature_names'])} features: "
        + ", ".join(f"`{f}`" for f in m["feature_names"]),
        f"- Answers: {m['n']['total']} (train {m['n']['train']} / calibration {m['n']['calibration']} / test {m['n']['test']}); "
        f"{_pct(m['hallucinated_share'])} labelled hallucinated",
        f"- Conformal alpha = {k['alpha']} (target coverage {_pct(k['target_coverage'])}); "
        f"guardrail uses the **{k['guardrail_variant'].replace('_', '-')}** variant",
        "",
        "## Classifier quality (test split)",
        "| Metric | Value |",
        "|---|---|",
        f"| Accuracy | {_pct(c['accuracy'])} |",
        f"| Accuracy of always guessing the majority class | {_pct(c['majority_baseline_accuracy'])} |",
        f"| AUROC | {_num(c['auroc'])} |",
        f"| AUROC using raw mean log-prob only | {_num(c.get('auroc_mean_logprob_only'))} |",
        f"| Brier score (lower is better) | {_num(c['brier'])} |",
        f"| Expected calibration error | {_num(c['ece'])} |",
        "",
        "## Conformal guardrail (test split)",
        "| Metric | Marginal | Class-conditional |",
        "|---|---|---|",
        f"| Coverage (target {_pct(k['target_coverage'])}) | {_pct(marg['coverage'])} | {_pct(cc['coverage'])} |",
        f"| Coverage on truly hallucinated answers | {_pct(marg['coverage_hallucinated'])} | {_pct(cc['coverage_hallucinated'])} |",
        f"| Coverage on truly factual answers | {_pct(marg['coverage_factual'])} | {_pct(cc['coverage_factual'])} |",
        f"| Average set size | {_num(marg['avg_set_size'], 2)} | {_num(cc['avg_set_size'], 2)} |",
        f"| TRUST (set = {{factual}}) | {_pct(marg['rate_trust'])} | {_pct(cc['rate_trust'])} |",
        f"| UNCERTAIN (both labels) | {_pct(marg['rate_uncertain'])} | {_pct(cc['rate_uncertain'])} |",
        f"| DON'T TRUST (set = {{hallucinated}}) | {_pct(marg['rate_flagged'])} | {_pct(cc['rate_flagged'])} |",
        f"| Hallucinations wrongly stamped TRUST | {_pct(marg['false_reassurance_rate'])} | {_pct(cc['false_reassurance_rate'])} |",
        f"| Precision of TRUST | {_pct(marg['trust_precision'])} | {_pct(cc['trust_precision'])} |",
        "",
    ]
    if rs:
        out += [
            "## Does the guarantee hold? (many random re-splits)",
            "| Variant | Re-splits | Mean coverage | 5th percentile | Mean set size | Mean wrongly-TRUST |",
            "|---|---|---|---|---|---|",
        ]
        for variant, r in rs.items():
            out.append(
                f"| {variant.replace('_', '-')} | {r['n_repeats']} | {_pct(r['coverage_mean'])} | {_pct(r['coverage_p05'])} "
                f"| {_num(r['avg_set_size_mean'], 2)} | {_pct(r['false_reassurance_mean'])} |"
            )
        out.append("")
    out += ["## Figures"] + [f"![{Path(f).stem}](figures/{f})" for f in figures] + [""]
    out += [
        "## Features used",
        *[f"- `{f}`: {FEATURE_DESCRIPTIONS[f]}" for f in m["feature_names"]],
        "",
        "## Read this before quoting the numbers",
        "- Labels come from a similarity rule (or an LLM judge), not human grading: they are a proxy for truth.",
        "- A single test split is small; prefer the re-split averages for judging the guarantee.",
        "- The guardrail measures the model's *confidence profile*, not truth: a confidently wrong answer can still get TRUST.",
        "",
    ]
    path = run_path / "REPORT.md"
    path.write_text("\n".join(out))
    return path
